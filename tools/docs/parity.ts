import type { Declarations, Load } from '../../src/composition/loader.ts';
import { OSES, featuresOf, provedOn, type AdapterDeclaration, type FeatureIdOf, type FeatureRow, type FeatureSide, type Support } from '../../src/plugin-api/index.ts';

/**
 * Draws docs/parity.md from what each adapter declares and the feature registry: a table per feature group with a
 * column per adapter, so the page saying what runs on which tool is never written by hand and never drifts from the
 * declarations the loader and the checks read.
 */

/** The page this module draws, from the repo root. */
export const PARITY_DOC = 'docs/parity.md';

const INTRO = [
  '# Feature parity',
  '',
  "<!-- Generated by `npm run docs:parity` from each adapter's declaration.ts under src/adapters and the feature registry (a file per group under src/features/host, src/features/connector and src/features/terminal): edit those, not this page. -->",
  '',
  'What each tool teamrig runs on supports, feature by feature, as its adapter declares it. After a declaration or the registry changes, `npm run check` fails until `npm run docs:parity` redraws this page.',
  '',
  'A cell reads:',
  '',
  '- **supported**: the feature runs on this tool. `proved on` names the operating systems with a live proof, the record of a run on a real install of the tool. A row counts as proved on an operating system only with a proof made there, so `unproved` says no such record exists yet, not that the feature fails.',
  '- **partial**: part of it runs. The cell says what is missing, then where the rest is proved.',
  '- **unsupported**: it does not run on this tool. The cell says why.',
  '',
];

const SIDES: { readonly [Side in FeatureSide]: { readonly title: string; readonly what: string } } = {
  host: { title: 'Hosts', what: 'The AI CLIs a session runs in.' },
  connector: { title: 'Connectors', what: "The outside tools holding a team's issues (the `tracker` rows) or its code and pull requests (the `codehost` rows)." },
  terminal: { title: 'Terminals', what: 'The programs whose panes the sessions run in.' },
};

/** Where a row that runs is proved, and where it is not yet. */
function proofWords(support: Support): string {
  const proved = provedOn(support);
  if (proved.length === 0) return 'unproved';
  const unproved = OSES.filter((os) => !proved.includes(os));
  const on = `proved on ${proved.join(', ')}`;
  return unproved.length === 0 ? on : `${on}; unproved on ${unproved.join(', ')}`;
}

function cell(support: Support): string {
  switch (support.kind) {
    case 'supported':
      return `supported, ${proofWords(support)}`;
    case 'partial':
      return `partial (missing: ${support.missing}), ${proofWords(support)}`;
    case 'unsupported':
      return `unsupported: ${support.notice}`;
  }
}

/** One table row; a cell's pipes are escaped (GitHub honours `\|` in code spans too) and newlines become spaces. */
function tableRow(cells: readonly string[]): string {
  return `| ${cells.map((cell) => cell.replace(/\r?\n/g, ' ').replaceAll('|', '\\|')).join(' | ')} |`;
}

/** The rows under the group each names, groups in the order their first row comes. */
function byGroup<Row extends FeatureRow>(rows: readonly Row[]): ReadonlyMap<string, readonly Row[]> {
  const groups = new Map<string, Row[]>();
  for (const row of rows) groups.set(row.group, [...(groups.get(row.group) ?? []), row]);
  return groups;
}

/** Why a side's declarations cannot be drawn: one line per refused adapter. */
function refusals(side: FeatureSide, loads: readonly Load<unknown>[]): readonly string[] {
  return loads.flatMap((load) => (load.kind === 'refused' ? [`the ${side} adapter ${load.id}: ${load.notices.join(', ')}`] : []));
}

function section<Side extends FeatureSide>(side: Side, loads: readonly Load<AdapterDeclaration<Side>>[]): readonly string[] {
  const adapters = loads.flatMap((load) => (load.kind === 'loaded' ? [load.value] : []));
  const head = [tableRow(['Feature', 'What it does', ...adapters.map((adapter) => adapter.name)]), tableRow(['---', '---', ...adapters.map(() => '---')])];
  const rowOf = (row: FeatureRow<FeatureIdOf<Side>>): string => tableRow([`\`${row.id}\``, row.doc, ...adapters.map((adapter) => cell(adapter.manifest[row.id]))]);
  return [
    `## ${SIDES[side].title}`,
    '',
    SIDES[side].what,
    '',
    ...adapters.map((adapter) => `- ${adapter.name} (\`${adapter.id}\`), built on plugin API ${adapter.apiVersion}`),
    '',
    ...[...byGroup(featuresOf(side))].flatMap(([group, rows]) => [`### ${group}`, '', ...head, ...rows.map(rowOf), '']),
  ];
}

/**
 * The page, ending in one newline. Throws when a declaration was refused, naming each one with its notices: a page
 * drawn without that adapter's column would read as if the tool were gone.
 */
export function renderParity(declarations: Declarations): string {
  const refused = [...refusals('host', declarations.hosts), ...refusals('connector', declarations.connectors), ...refusals('terminal', declarations.terminals)];
  if (refused.length > 0) throw new Error(`a refused declaration cannot be drawn: ${refused.join('; ')}`);
  const lines = [...INTRO, ...section('host', declarations.hosts), ...section('connector', declarations.connectors), ...section('terminal', declarations.terminals)];
  return `${lines.join('\n').trimEnd()}\n`;
}
