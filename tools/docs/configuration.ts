import { readFileSync } from 'node:fs';
import { isRecord, isStringArray, numberField, recordField, stringField, type JsonRecord } from '../../src/core/guards.ts';
import { headingAnchors } from './doc-check.ts';

/**
 * Draws docs/configuration.md from the config's JSON schema: a section per object that lists keys, each key with its
 * type, default and description, so the reference page is never written by hand and never drifts from the schema.
 */

/** The page this module draws, from the repo root. */
export const CONFIG_DOC = 'docs/configuration.md';
/** The schema it draws from, from the repo root. */
export const CONFIG_SCHEMA = 'plugins/teamrig/config.schema.json';
const SCHEMA_URL = new URL(`../../${CONFIG_SCHEMA}`, import.meta.url);

const TITLE = 'Configuration reference';
const TOP_LEVEL = 'Top level';
const SHARED_TYPES = 'Shared types';
const TABLE_HEAD = ['| Key | Type | Default | What it does |', '| --- | --- | --- | --- |'];
const SHARED_HEAD = ['| Name | Type | What it is |', '| --- | --- | --- |'];
const DEF_REF = /^#\/\$defs\/([A-Za-z][A-Za-z0-9]*)$/;
/**
 * The schema keywords this page knows: it draws each one, or for `$schema`, `$id` and `title` has nothing to draw.
 * Any other keyword throws, so a rule added to the schema never goes missing from the page unnoticed.
 */
const KEYWORDS: ReadonlySet<string> = new Set([
  '$schema', '$id', 'title', 'description', 'type', 'required', 'properties', '$defs', '$ref', 'anyOf', 'enum', 'default',
  'minimum', 'maximum', 'minLength', 'maxLength', 'pattern', 'items', 'minItems', 'maxItems', 'uniqueItems',
  'additionalProperties', 'propertyNames',
]);

/** An object that lists keys, drawn as one section. */
interface Section {
  /** Dotted, with `[]` for an array's items and `*` for a map's values; '' for the top level. */
  readonly path: string;
  readonly heading: string;
  readonly description: string | undefined;
  readonly node: JsonRecord;
}

interface Anchors {
  /** Each section's heading anchor, by path. */
  readonly anchors: ReadonlyMap<string, string>;
  readonly sharedAnchor: string;
}

interface Context extends Anchors {
  readonly defs: JsonRecord;
}

/** The config schema from the repo. */
export function loadConfigSchema(): JsonRecord {
  const parsed: unknown = JSON.parse(readFileSync(SCHEMA_URL, 'utf8'));
  if (!isRecord(parsed)) throw new Error(`${CONFIG_SCHEMA} is not a JSON object`);
  return parsed;
}

/** The whole reference page for `schema`, ending in a newline. */
export function renderConfigReference(schema: JsonRecord): string {
  checkKeywords(schema, '');
  const defs = recordField(schema, '$defs') ?? {};
  const sections: Section[] = [];
  collectSections(schema, '', undefined, sections);
  const context: Context = { ...sectionAnchors(sections, Object.keys(defs).length > 0), defs };
  const intro = [
    `# ${TITLE}`,
    `<!-- Generated by \`npm run docs:config\` from ${CONFIG_SCHEMA}: edit the schema, not this page. -->`,
    `Every key of a team's \`<kit home>/teams/<team>/config.json\`, drawn from [its JSON schema](../${CONFIG_SCHEMA}). ` +
      "A key's words are its `description` there: edit them in the schema, and `npm run check` fails until `npm run docs:config` redraws this page. " +
      '[Set up a team by hand](setup-by-hand.md#configuration) starts from a small config.',
    "Values are shown as JSON; a map's keys as `*`, an array's items as `[]`.",
  ];
  const shared = Object.keys(defs).length > 0 ? [renderSharedTypes(context)] : [];
  return `${[...intro, ...sections.map((section) => renderSection(section, context)), ...shared].join('\n\n')}\n`;
}

function checkKeywords(node: JsonRecord, path: string): void {
  const unknown = Object.keys(node).find((keyword) => !KEYWORDS.has(keyword));
  if (unknown !== undefined) throw new Error(`config reference: the schema keyword ${unknown} at ${label(path)} is not drawn`);
  for (const [key, child] of properties(node)) checkKeywords(child, keyPath(path, key));
  const defs = recordField(node, '$defs') ?? {};
  for (const [name, def] of Object.entries(defs)) if (isRecord(def)) checkKeywords(def, `$defs.${name}`);
  for (const branch of branches(node)) checkKeywords(branch, path);
  const nested: readonly [string, string][] = [['items', `${path}[]`], ['additionalProperties', `${path}.*`], ['propertyNames', `${path} keys`]];
  for (const [keyword, nestedPath] of nested) {
    const child = recordField(node, keyword);
    if (child !== undefined) checkKeywords(child, nestedPath);
  }
}

/** Every object that lists keys, depth first in schema order; an item or map value object without words takes its holder's. */
function collectSections(node: JsonRecord, path: string, inherited: string | undefined, out: Section[]): void {
  const description = stringField(node, 'description') ?? inherited;
  const value = recordField(node, 'additionalProperties');
  if (properties(node).length > 0) {
    if (value !== undefined) throw new Error(`config reference: ${label(path)} lists keys and is a map; the page draws one or the other`);
    out.push({ path, heading: path === '' ? TOP_LEVEL : code(path), description, node });
  }
  for (const [key, child] of properties(node)) collectSections(child, keyPath(path, key), undefined, out);
  const item = recordField(node, 'items');
  if (item !== undefined) collectSections(item, `${path}[]`, description, out);
  if (value !== undefined) collectSections(value, `${path}.*`, description, out);
}

/** Each heading's anchor as GitHub makes it; throws when two headings of the page would share one. */
function sectionAnchors(sections: readonly Section[], hasShared: boolean): Anchors {
  const owners = new Map<string, string>();
  const claim = (heading: string): string => {
    const [anchor] = headingAnchors(`## ${heading}`);
    if (anchor === undefined) throw new Error(`config reference: the heading ${heading} has no anchor`);
    const owner = owners.get(anchor);
    if (owner !== undefined) throw new Error(`config reference: the headings ${owner} and ${heading} share the anchor #${anchor}`);
    owners.set(anchor, heading);
    return anchor;
  };
  claim(TITLE);
  const anchors = new Map(sections.map((section) => [section.path, claim(section.heading)] as const));
  return { anchors, sharedAnchor: hasShared ? claim(SHARED_TYPES) : '' };
}

function renderSection(section: Section, context: Context): string {
  const required = new Set(isStringArray(section.node['required']) ? section.node['required'] : []);
  const rows = properties(section.node).map(([key, node]) => {
    const name = `${code(key)}${required.has(key) ? ' (required)' : ''}`;
    const fallback = 'default' in node ? code(JSON.stringify(node['default'])) : '';
    return tableRow([name, typeText(node, keyPath(section.path, key), context), fallback, prose(stringField(node, 'description') ?? '')]);
  });
  const words = section.description === undefined ? [] : [prose(section.description)];
  return [`## ${section.heading}`, ...words, [...TABLE_HEAD, ...rows].join('\n')].join('\n\n');
}

function renderSharedTypes(context: Context): string {
  const rows = Object.entries(context.defs).flatMap(([name, def]) =>
    isRecord(def) ? [tableRow([words(name), typeText(def, `$defs.${name}`, context), prose(stringField(def, 'description') ?? '')])] : [],
  );
  return [`## ${SHARED_TYPES}`, [...SHARED_HEAD, ...rows].join('\n')].join('\n\n');
}

/** What a value at `path` may be, in words. */
function typeText(node: JsonRecord, path: string, context: Context): string {
  const ref = stringField(node, '$ref');
  if (ref !== undefined) return sharedTypeLink(ref, path, context);
  const options = branches(node);
  if (options.length > 0) return options.map((branch) => typeText(branch, path, context)).join(' or ');
  const values = node['enum'];
  if (Array.isArray(values)) return `one of ${values.map((value) => code(JSON.stringify(value))).join(', ')}`;
  const type = node['type'];
  switch (type) {
    case 'object':
      return objectText(node, path, context);
    case 'array':
      return arrayText(node, path, context);
    case 'integer':
    case 'number':
      return withLimits(type, [rangeText(numberField(node, 'minimum'), numberField(node, 'maximum'), undefined)]);
    case 'string': {
      const pattern = stringField(node, 'pattern');
      const length = rangeText(numberField(node, 'minLength'), numberField(node, 'maxLength'), 'character');
      return withLimits('string', [length, pattern === undefined ? undefined : `matching ${code(pattern)}`]);
    }
    case 'boolean':
      return 'boolean';
    default:
      throw new Error(`config reference: ${label(path)} has no type the page can draw`);
  }
}

function objectText(node: JsonRecord, path: string, context: Context): string {
  const anchor = context.anchors.get(path);
  if (anchor !== undefined) return `[object](#${anchor})`;
  const value = recordField(node, 'additionalProperties');
  if (value === undefined) return 'object';
  // A key is always a string, so a key schema that names no type (only a pattern, say) is a string one.
  const keys = recordField(node, 'propertyNames');
  const keyText = keys === undefined ? 'string' : typeText({ type: 'string', ...keys }, `${path} keys`, context);
  return `map from ${keyText} to ${typeText(value, `${path}.*`, context)}`;
}

function arrayText(node: JsonRecord, path: string, context: Context): string {
  const count = rangeText(numberField(node, 'minItems'), numberField(node, 'maxItems'), 'item');
  const head = withLimits('array', [count, node['uniqueItems'] === true ? 'unique' : undefined]);
  const item = recordField(node, 'items');
  return item === undefined ? head : `${head} of ${typeText(item, `${path}[]`, context)}`;
}

function sharedTypeLink(ref: string, path: string, context: Context): string {
  const name = DEF_REF.exec(ref)?.[1];
  if (name === undefined || !isRecord(context.defs[name])) throw new Error(`config reference: ${label(path)} refers to ${ref}, which is not in $defs`);
  return `[${words(name)}](#${context.sharedAnchor})`;
}

/** `1 to 9 items`, `at least 1 item`, `at most 64`; undefined when neither bound is set. */
function rangeText(min: number | undefined, max: number | undefined, unit: string | undefined): string | undefined {
  const counted = (n: number): string => (unit === undefined ? `${n}` : `${n} ${unit}${n === 1 ? '' : 's'}`);
  if (min !== undefined && max !== undefined) return `${min} to ${counted(max)}`;
  if (min !== undefined) return `at least ${counted(min)}`;
  if (max !== undefined) return `at most ${counted(max)}`;
  return undefined;
}

function withLimits(name: string, limits: readonly (string | undefined)[]): string {
  const set = limits.filter((limit): limit is string => limit !== undefined);
  return set.length === 0 ? name : `${name} (${set.join(', ')})`;
}

function properties(node: JsonRecord): [string, JsonRecord][] {
  return Object.entries(recordField(node, 'properties') ?? {}).filter((entry): entry is [string, JsonRecord] => isRecord(entry[1]));
}

function branches(node: JsonRecord): JsonRecord[] {
  const anyOf = node['anyOf'];
  return Array.isArray(anyOf) ? anyOf.filter(isRecord) : [];
}

function keyPath(path: string, key: string): string {
  return path === '' ? key : `${path}.${key}`;
}

function label(path: string): string {
  return path === '' ? 'the top level' : path;
}

/** `sessionName` → `session name`. */
function words(name: string): string {
  return name.replace(/([a-z0-9])([A-Z])/g, '$1 $2').toLowerCase();
}

/** A code span; doubled backticks when the text holds one. */
function code(text: string): string {
  return text.includes('`') ? `\`\` ${text} \`\`` : `\`${text}\``;
}

/** Schema words as Markdown: outside code spans, characters Markdown would read as markup are escaped. */
function prose(text: string): string {
  return text
    .split(/(`[^`]*`)/)
    .map((part, index) => (index % 2 === 1 ? part : part.replace(/[\\*_<~]/g, '\\$&')))
    .join('');
}

/** One table row; a cell's pipes are escaped (GitHub honours `\|` in code spans too) and newlines become spaces. */
function tableRow(cells: readonly string[]): string {
  return `| ${cells.map((cell) => cell.replace(/\r?\n/g, ' ').replaceAll('|', '\\|')).join(' | ')} |`;
}
